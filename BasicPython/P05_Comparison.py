print("Here you can see the use of the comparison operators:")
num1 = 5
num2 = 3
print(f"Example numbers: {num1} and {num2}")
print(f"({num1} < {num2}): {num1} is less than {num2}?: {num1 < num2}")
print(f"({num1} <= {num2}): {num1} is less or equal than {num2}?: {num1 <= num2}")
print(f"({num1} > {num2}): {num1} is  greater than {num2}?: {num1 > num2}")
print(f"({num1} >= {num2}): {num1} is  greater or equal than {num2}?: {num1 >= num2}")
print(f"({num1} == {num2}): {num1} is  equal than {num2}?: {num1 == num2}")
print(f"({num1} != {num2}): {num1} is  different than {num2}?: {num1 != num2}")
print("\nRemember that one equal '=' is used to assign a value to a variable.\n")